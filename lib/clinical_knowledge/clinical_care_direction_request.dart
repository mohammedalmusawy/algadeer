import '../search/arabic_text_utils.dart';

/// سؤال «وين توجهني؟» داخل محادثة سريرية قائمة — طلب وجهة، لا شكوى ولا اسم.
///
/// كل حزمة سريرية تعرف أصلاً هذا المعنى باسم `asksServiceWhere`، لكن مفرداته
/// كانت محصورة بـ«وين اروح / منو اراجع / منو الطبيب». الصياغات العراقية
/// الطبيعية الأخرى («وين توجهني»، «وين اتوجه»، «شنو تنصحني») ما كانت تُطابق،
/// فيرجع `mayHandle` كذباً، ويسقط الدور من تحكيم PC-1.24، فيلتقط مسار اسم
/// الطبيب البقية بعد قصّ «وين» ويبحث حرفياً عن «توجهني» → «ما لقيت نتيجة
/// مطابقة حالياً.». هذا المصدر الواحد يوسّع نفس المعنى القائم بلا تكراره.
///
/// يُستشار حصراً عندما تكون الجلسة **نشطة**: هذه صياغات استمرار لا تفتح
/// موضوعاً سريرياً جديداً، وإلا لسحبت أسئلة عامة مثل «شنو تنصحني» من مسارها
/// الوقائي القائم (PC-1.7).
class ClinicalCareDirectionRequest {
  const ClinicalCareDirectionRequest._();

  /// «وين توجهني / وين اتوجه / وين أراجع / وين تنصحني».
  static final RegExp _whereToGo = RegExp(
    r'(?:^|\s)(?:وين|اين|لوين)\s*'
    r'(?:اتوجه|توجهني|وجهني|تدلني|تنصحني|اراجع|راجع|اروح|اشوف)(?:\s|$)',
  );

  /// «أي اختصاص أراجع / أي طبيب أراجع» — يلزمه فعل توجيه صريح حتى لا يُقرأ
  /// طلب طبيب عادياً كسؤال وجهة.
  static final RegExp _whichSpecialty = RegExp(
    r'(?:^|\s)(?:اي|ايه|منو|شنو)\s*(?:ال)?'
    r'(?:اختصاص|تخصص|طبيب|دكتور)\s*'
    r'(?:اراجع|راجع|اروح|اشوف|يناسبني|المناسب)(?:\s|$)',
  );

  /// «شنو تنصحني / شنو تنصحني اسوي / شنو الخطوة الجاية».
  static final RegExp _whatDoYouAdvise = RegExp(
    r'(?:^|\s)(?:شنو|شني|شو|ايش)\s*'
    r'(?:تنصحني|تنصح|توصيني|الخطوه)(?:\s|$)',
  );

  /// هل هذا الدور سؤال عن وجهة الرعاية التالية؟
  static bool matches(String raw) {
    final n = ArabicTextUtils.normalize(raw);
    if (n.isEmpty) return false;
    return _whereToGo.hasMatch(n) ||
        _whichSpecialty.hasMatch(n) ||
        _whatDoYouAdvise.hasMatch(n);
  }
}
